import apiClient from './api'
import type {
  AnalyticsSummary,
  AnalyticsOverview,
  TrendDataPoint,
  CategoryBreakdownItem,
  BudgetPerformanceItem,
  FinancialInsight,
  AnalyticsQueryParams,
} from '../types/analytics'
import type { DailySpending } from '../types/finance'

export interface ApiResponse<T> {
  success: boolean
  data: T
}

export const analyticsService = {
  /**
   * Fetch full financial overview with current period, previous period baseline, and deltas
   */
  async getOverview(params: AnalyticsQueryParams = {}): Promise<AnalyticsOverview> {
    const response = await apiClient.get<ApiResponse<AnalyticsOverview>>('/analytics/overview', {
      params,
    })
    return response.data.data
  },

  /**
   * Fetch multi-series dynamic trends (income, expenses, netCashFlow)
   */
  async getTrends(params: AnalyticsQueryParams = {}): Promise<TrendDataPoint[]> {
    const response = await apiClient.get<ApiResponse<TrendDataPoint[]>>('/analytics/trends', {
      params,
    })
    return response.data.data
  },

  /**
   * Fetch rule-based financial insights generated by backend engine
   */
  async getInsights(params: AnalyticsQueryParams = {}): Promise<FinancialInsight[]> {
    const response = await apiClient.get<ApiResponse<FinancialInsight[]>>('/analytics/insights', {
      params,
    })
    return response.data.data
  },

  /**
   * Fetch categorical expense breakdown
   */
  async getCategoryBreakdown(params: AnalyticsQueryParams = {}): Promise<CategoryBreakdownItem[]> {
    const response = await apiClient.get<ApiResponse<CategoryBreakdownItem[]>>(
      '/analytics/categories',
      { params }
    )
    return response.data.data
  },

  /**
   * Fetch summary metrics
   */
  async getSummary(params: AnalyticsQueryParams = {}): Promise<AnalyticsSummary> {
    const response = await apiClient.get<ApiResponse<AnalyticsSummary>>('/analytics/summary', {
      params,
    })
    return response.data.data
  },

  /**
   * Fetch legacy 7-30 day spending trend
   */
  async getSpendingTrend(days: number = 7): Promise<DailySpending[]> {
    const response = await apiClient.get<ApiResponse<DailySpending[]>>(
      '/analytics/spending-trend',
      {
        params: { days },
      }
    )
    return response.data.data
  },

  /**
   * Fetch budget performance
   */
  async getBudgetPerformance(): Promise<BudgetPerformanceItem[]> {
    const response = await apiClient.get<ApiResponse<BudgetPerformanceItem[]>>(
      '/analytics/budget-performance'
    )
    return response.data.data
  },
}
